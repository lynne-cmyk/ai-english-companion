import { Resvg } from "@resvg/resvg-js";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const brand = path.join(root, "assets/brand");
const output = path.join(brand, "generated");
mkdirSync(output, { recursive: true });
const glyph = readFileSync(path.join(brand, "brand-glyph-app.svg"), "utf8")
  .replace(/<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const template = readFileSync(path.join(brand, "brand-glyph-menubar-template.svg"), "utf8");

// 864px ceramic body within a transparent 1024px macOS canvas. Scaling the
// 512px glyph master keeps its locked 56% body-height ratio without redrawing.
const artwork = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by scripts/generate-brand-assets.mjs; edit the SVG masters. -->
  <defs>
    <linearGradient id="ceramic" x1="0" y1="0" x2="0" y2="1">
      <stop stop-color="#FBFAFF"/><stop offset="1" stop-color="#F2F0FB"/>
    </linearGradient>
    <filter id="depth" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="12" stdDeviation="12" flood-color="#202938" flood-opacity="0.10"/>
    </filter>
  </defs>
  <rect x="80" y="80" width="864" height="864" rx="194.064" fill="url(#ceramic)" filter="url(#depth)"/>
  <rect x="80.5" y="80.5" width="863" height="863" rx="193.564" fill="none" stroke="#6B5FED" stroke-opacity="0.09"/>
  <g transform="translate(80 80) scale(1.6875)">${glyph}</g>
</svg>\n`;
writeFileSync(path.join(output, "app-icon.svg"), artwork);
const render = (svg, size) => new Resvg(svg, { fitTo: { mode: "width", value: size } }).render().asPng();
const rasters = new Map();
for (const size of [16, 32, 64, 128, 256, 512, 1024]) {
  const png = render(artwork, size);
  rasters.set(size, png);
  // Intermediate ICNS sizes remain in the temporary iconset only.
  if ([32, 64, 128, 512, 1024].includes(size)) {
    writeFileSync(path.join(output, size === 1024 ? "app-icon.png" : `app-icon-${size}.png`), png);
  }
}
const tray1x = render(template, 16);
const tray2x = render(template, 32);
writeFileSync(path.join(output, "menuBarTemplate.png"), tray1x);
writeFileSync(path.join(output, "menuBarTemplate@2x.png"), tray2x);
writeFileSync(path.join(root, "electron/permissions/menuBarIconData.ts"),
  `// Generated from assets/brand/brand-glyph-menubar-template.svg. Do not edit.\n` +
  `export const MENU_BAR_ICON_LOGICAL_SIZE = 16;\n` +
  `export const MENU_BAR_ICON_1X_PNG_BASE64 = "${tray1x.toString("base64")}";\n` +
  `export const MENU_BAR_ICON_2X_PNG_BASE64 = "${tray2x.toString("base64")}";\n`);

if (process.platform !== "darwin") throw new Error("ICNS generation requires macOS iconutil.");
const temporary = mkdtempSync(path.join(tmpdir(), "ai-english-brand-"));
try {
  const iconset = path.join(temporary, "app.iconset");
  mkdirSync(iconset);
  for (const size of [16, 32, 128, 256, 512]) {
    writeFileSync(path.join(iconset, `icon_${size}x${size}.png`), rasters.get(size));
    writeFileSync(path.join(iconset, `icon_${size}x${size}@2x.png`), rasters.get(size * 2));
  }
  execFileSync("iconutil", ["-c", "icns", "-o", path.join(output, "app-icon.icns"), iconset]);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
console.log("Generated App Icon PNG/ICNS and dedicated 16/32px Menu Bar template assets.");
